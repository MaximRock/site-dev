import { readFile, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const TOKENS_DIR = join(ROOT, "tokens");
const OUTPUT = join(ROOT, "src", "styles", "tokens.css");

const files = (await readdir(TOKENS_DIR)).filter((file) => file.endsWith(".json")).sort();

const definitions = new Map();

function flatten(node, prefix = "") {
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    const path = prefix ? `${prefix}.${key}` : key;
    if (value && typeof value === "object" && "$value" in value) {
      definitions.set(path, value);
    } else if (value && typeof value === "object") {
      flatten(value, path);
    }
  }
}

for (const file of files) {
  const content = JSON.parse(await readFile(join(TOKENS_DIR, file), "utf8"));
  flatten(content);
}

function resolve(path, stack = []) {
  if (stack.includes(path)) {
    throw new Error(`Circular token reference: ${[...stack, path].join(" -> ")}`);
  }
  const token = definitions.get(path);
  if (!token) {
    throw new Error(`Unknown token reference: ${path}`);
  }
  const value = token.$value;
  if (typeof value === "string" && /^\{[^}]+\}$/.test(value)) {
    return resolve(value.slice(1, -1), [...stack, path]);
  }
  return value;
}

function formatValue(value, type) {
  if (Array.isArray(value)) {
    if (type === "cubicBezier" && value.length === 4) {
      return `cubic-bezier(${value.join(", ")})`;
    }
    return value.join(", ");
  }
  return String(value);
}

function cssName(path) {
  if (path.startsWith("semantic.")) {
    return `--color-${path.slice("semantic.".length).replaceAll(".", "-")}`;
  }
  if (path.startsWith("primitive.")) {
    return `--color-primitive-${path.slice("primitive.".length).replaceAll(".", "-")}`;
  }
  return `--${path.replaceAll(".", "-")}`;
}

const lines = [
  "/* Generated by scripts/build-tokens.mjs. Do not edit by hand. */",
  ":root {",
  "  color-scheme: light;",
];

for (const [path, token] of [...definitions.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  const value = formatValue(resolve(path), token.$type);
  lines.push(`  ${cssName(path)}: ${value};`);
}

lines.push("}");
await writeFile(OUTPUT, `${lines.join("\n")}\n`, "utf8");
console.log(`build-tokens: wrote ${definitions.size} tokens to src/styles/tokens.css`);
